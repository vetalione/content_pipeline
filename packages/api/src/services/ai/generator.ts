function createGenerationPrompt(
  celebrityName: string,
  researchData: any,
  styleConfig?: Partial<StyleConfig>
): string {
  // Extract facts count from research data
  const factsCount = researchData?.facts?.length || 9;
  const pointsCount = styleConfig?.pointsCount || factsCount;
  
  // Extract quotes for easy reference
  const quotes = researchData?.quotes || [];
  const quotesText = quotes.length > 0 
    ? `\n\n📣 ЦИТАТЫ ГЕРОЯ (используй их в статье):\n${quotes.map((q: any) => `• "${q.text}" — ${q.context || q.source || ''}`).join('\n')}`
    : '';
  
  return `
═══════════════════════════════════════════════════════════════
📋 ЗАДАНИЕ: Создай статью про ${celebrityName}
═══════════════════════════════════════════════════════════════

Используй данные исследования ниже. Статья должна содержать ${pointsCount} пунктов-неудач.
${quotesText}

═══════════════════════════════════════════════════════════════
📊 ДАННЫЕ ИССЛЕДОВАНИЯ:
═══════════════════════════════════════════════════════════════

${JSON.stringify(researchData, null, 2)}

═══════════════════════════════════════════════════════════════
✅ ТРЕБОВАНИЯ К СТАТЬЕ:
═══════════════════════════════════════════════════════════════

1. Заголовок: "${pointsCount} неудач ${celebrityName}" (или похожий формат)

2. Тизер: Начни с того, чем ${celebrityName} известен и любим, затем через "НО" 
   добавь 2-3 шокирующих контрастных факта из исследования для интриги.

3. Основные пункты (${pointsCount} штук):
   • Каждый пункт = одна неудача из research.facts
   • СТРОГО хронологический порядок (от детства к зрелости)
   • В каждом пункте: заголовок + 2-4 предложения с конкретикой
   • imageHint: опиши какое фото/мем нужен (приоритет: фото героя)
   • quote: добавляй цитаты или ироничные комментарии через каждые 2-3 пункта

4. Итог: Контраст "а теперь..." с конкретными цифрами успеха + цитата героя

5. Брендовая концовка: Стандартная фраза про "Великих Неудачников"

6. Стиль: Ироничный, позитивный, БЕЗ драмы и хейта. Приглашаем посмеяться вместе.

Верни ТОЛЬКО валидный JSON без дополнительного текста.
`;
}
