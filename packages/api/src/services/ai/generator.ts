import Anthropic from '@anthropic-ai/sdk';
import { prisma } from '../../lib/db';
import { PipelineStage, ArticleContent, StyleConfig } from '@content-pipeline/shared';

const anthropic = new Anthropic({
  apiKey: process.env.ANTHROPIC_API_KEY
});

/**
 * Generate article content from research data
 */
export async function generateContent(
  articleId: string,
  styleConfig?: Partial<StyleConfig>
): Promise<ArticleContent> {
  const article = await prisma.article.findUnique({
    where: { id: articleId }
  });
  
  if (!article) {
    throw new Error('Article not found');
  }
  
  if (!article.researchData) {
    throw new Error('No research data available. Run research first.');
  }
  
  console.log(`Generating content for ${article.celebrityName} using Claude Sonnet 4.5...`);
  
  const style = (article as any).articleStyle === 'rasplata' ? 'rasplata' : 'basic';
  console.log(`📐 Article style: ${style}`);

  const systemPrompt = style === 'rasplata' ? getRasplataSystemPrompt() : getSystemPrompt();
  const userPrompt = createGenerationPrompt(article.celebrityName, article.researchData, styleConfig);
  
  const message = await anthropic.messages.create({
    model: 'claude-sonnet-4-20250514',
    max_tokens: 16000,
    messages: [
      {
        role: 'user',
        content: userPrompt
      }
    ],
    system: systemPrompt
  });
  
  // Extract text from response
  const responseText = message.content[0].type === 'text' ? message.content[0].text : '';
  
  // Parse JSON from response (handle markdown code blocks)
  let jsonStr = responseText.trim();
  if (jsonStr.startsWith('```json')) {
    jsonStr = jsonStr.replace(/^```json\s*\n?/, '').replace(/\n?```\s*$/, '');
  } else if (jsonStr.startsWith('```')) {
    jsonStr = jsonStr.replace(/^```\s*\n?/, '').replace(/\n?```\s*$/, '');
  }
  
  let content;
  try {
    content = JSON.parse(jsonStr);
  } catch (parseError) {
    console.error('❌ JSON parse error:', parseError);
    console.log('📄 Raw response (first 500 chars):', responseText.substring(0, 500));
    console.log('📄 Problematic JSON around position 3017:', jsonStr.substring(2900, 3100));
    
    // Try to fix common JSON issues
    try {
      // Fix unescaped quotes in strings
      let fixedJson = jsonStr
        // Fix unescaped newlines in strings
        .replace(/\\n/g, '\\\\n')
        // Fix unescaped quotes (but not already escaped ones)
        .replace(/([^\\])"([^"]*)"([^:])/g, '$1\\"$2\\"$3');
      
      content = JSON.parse(fixedJson);
      console.log('✅ Successfully parsed after fixing JSON');
    } catch (retryError) {
      console.error('❌ Failed to parse JSON even after fixes');
      console.log('Full response:', responseText);
      throw new Error(`Failed to parse Claude response: ${parseError instanceof Error ? parseError.message : 'Unknown error'}`);
    }
  }
  
  // Note: Image matching is now done in autopilot.ts AFTER article generation
  // This allows us to search images specifically for the generated sections
  
  // Save to database
  await prisma.article.update({
    where: { id: articleId },
    data: {
      content,
      currentStage: PipelineStage.GENERATION,
      updatedAt: new Date()
    }
  });
  
  return content;
}

